const createRecipeLine = (inventoryMap, ingredientName, quantity) => {
  const item = inventoryMap.get(ingredientName);
  if (!item) {
    throw new Error(`Missing inventory item for recipe mapping: ${ingredientName}`);
  }

  return {
    inventory_id: item.id,
    ingredient_name: item.name,
    quantity,
    unit: item.unit,
  };
};

