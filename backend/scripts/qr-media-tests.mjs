import assert from "node:assert/strict";
import { randomUUID } from "node:crypto";
import http from "node:http";
import app from "../src/app.js";
import prisma from "../src/database/prisma/client.js";
import env from "../src/config/env.js";
import { productsService } from "../src/core/products/products.service.js";
import { validateProductImage } from "../src/core/products/product-images.js";
import { tableManagementService } from "../src/features/sales-extensions/table-management/table-management.service.js";
import { qrOrderingService } from "../src/features/sales-extensions/qr-ordering/qr-ordering.service.js";
import { runTenantScope } from "../src/database/prisma/tenant-context.js";
import { smsService } from "../src/services/sms/sms.service.js";

const id = `qr-media-${randomUUID()}`;
const tenantId = `tenant-${id}`;
const foreign = `${id}-foreign`;
const image = "data:image/png;base64,iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+jA8sAAAAASUVORK5CYII=";
const api = http.createServer(app);
const previousEnabled = env.admincore.enabled;
const previousNodeEnv = env.nodeEnv;
const previousSmsConfigured = smsService.configured;
try {
  env.admincore.enabled = false;
  await prisma.business.create({ data: { id, tenantId, name: "QR photo fixture" } });
  await prisma.business.create({ data: { id: foreign, tenantId: `tenant-${foreign}`, name: "Foreign fixture" } });
  await prisma.tableManagementSettings.create({ data: { businessId: id, capabilities: { qrOrderingEnabled: true } } });
  const product = await productsService.createProduct({ tenantId, payload: { name: "Photo item", category: "Food", price: 10, stock: 20, image_url: image } });
  assert.ok(product.image_url.includes(`/product-images/${id}/`));
  assert.equal((await productsService.getProductById({ tenantId, productId: product.id })).image_url, product.image_url);
  await assert.rejects(productsService.updateProduct({ tenantId, productId: product.id, payload: { name: "Should roll back", image_url: "javascript:alert(1)" } }));
  assert.equal((await prisma.product.findUnique({ where: { id: product.id } })).name, "Photo item");
  assert.throws(() => validateProductImage("data:image/svg+xml;base64,PHN2Zz4="));
  assert.throws(() => validateProductImage("data:image/png;base64,YmFk"));
  const table = await prisma.diningTable.create({ data: { businessId: id, name: "Photo table" } });
  const qr = await tableManagementService.upsertTableQrCode({ tenantId, businessId: id, tableId: table.id });
  const menu = await qrOrderingService.getMenu({ token: qr.token });
  assert.equal(menu.items.find((item) => item.id === product.id).image_url, product.image_url);
  env.nodeEnv = "development";
  smsService.configured = () => false;
  await runTenantScope({}, async () => {
    const issued = await qrOrderingService.requestPhoneVerification({ token: qr.token, phone: "9999999999" });
    assert.ok(issued.dev_otp);
    const verified = await qrOrderingService.verifyPhone({ token: qr.token, verificationToken: issued.verification_token, otp: issued.dev_otp });
    assert.equal(verified.verified, true);
    const rate = await prisma.stateDocument.findUnique({ where: { key: `qr-otp-rate:${id}:9999999999` } });
    assert.equal(rate.data.business_id, id);
    assert.equal(rate.data.sent_at.length, 1);
  });
  env.nodeEnv = previousNodeEnv;
  smsService.configured = previousSmsConfigured;
  await new Promise((resolve) => api.listen(0, "127.0.0.1", resolve));
  const base = `http://127.0.0.1:${api.address().port}`;
  const asset = await fetch(base + product.image_url);
  assert.equal(asset.status, 200);
  assert.match(asset.headers.get("content-type"), /image\/png/);
  assert.deepEqual(Buffer.from(await asset.arrayBuffer()), Buffer.from(image.split(",")[1], "base64"));
  assert.equal((await fetch(`${base}/api/public/qr/product-images/${foreign}/${product.id}`)).status, 404);
  assert.equal((await fetch(`${base}/api/table-management/${table.id}/qr`, { method: "DELETE" })).status, 401);
  await assert.rejects(tableManagementService.deleteTableQrCode({ tenantId: `tenant-${foreign}`, businessId: foreign, tableId: table.id }));
  assert.ok(await prisma.tableQrCode.findUnique({ where: { token: qr.token } }));
  await tableManagementService.deleteTableQrCode({ tenantId, businessId: id, tableId: table.id });
  await assert.rejects(qrOrderingService.resolveContext(qr.token));
  assert.ok(await prisma.diningTable.findUnique({ where: { id: table.id } }));
  assert.ok(await prisma.tableSession.findFirst({ where: { tableId: table.id } }));
  const next = await tableManagementService.upsertTableQrCode({ tenantId, businessId: id, tableId: table.id });
  assert.notEqual(next.token, qr.token);
  await productsService.updateProduct({ tenantId, productId: product.id, payload: { image_url: null } });
  assert.equal((await productsService.getProductById({ tenantId, productId: product.id })).image_url, null);
  assert.equal((await fetch(base + product.image_url)).status, 404);
  await productsService.updateProduct({ tenantId, productId: product.id, payload: { image_url: image } });
  await productsService.deleteProduct({ tenantId, productId: product.id });
  assert.equal(await prisma.stateDocument.findUnique({ where: { key: `product-image:${id}:${product.id}` } }), null);
  console.log("QR media passed: saved photo, public image, menu parity, invalid image rollback, tenant isolation, QR deletion/regeneration and preserved table/session");
} finally {
  if (api.listening) await new Promise((resolve) => api.close(resolve));
  env.admincore.enabled = previousEnabled;
  env.nodeEnv = previousNodeEnv;
  smsService.configured = previousSmsConfigured;
  await prisma.business.deleteMany({ where: { id: { in: [id, foreign] } } });
  await prisma.stateDocument.deleteMany({ where: { key: { contains: id } } });
  await prisma.stateDocument.deleteMany({ where: { data: { path: ["business_id"], equals: id } } });
  await prisma.$disconnect();
}
