// Regenerate only when intentionally adding/changing a tenant model policy.
import { Prisma } from "@prisma/client";
import { mkdir, writeFile } from "node:fs/promises";
import { tenantModelPaths, systemModels } from "../src/database/prisma/tenant-guard.js";
import { ROLE_DEFAULT_PERMISSIONS, STAFF_PERMISSION_KEYS } from "../src/shared/constants/access.constants.js";

const models = new Map(Prisma.dmmf.datamodel.models.map((model) => [model.name, model]));
const qi = (name) => `"${name.replaceAll('"', '""')}"`;
const lit = (value) => `'${value.replaceAll("'", "''")}'`;
const table = (name) => `public.${qi(models.get(name).dbName || name)}`;
const business = `NULLIF(current_setting('pos.business_id', true), '')`;
const tenant = `NULLIF(current_setting('pos.tenant_id', true), '')`;
const owner = (name, alias, depth = 0) => {
  if (name === "Business") return `${alias}."id"`;
  const path = tenantModelPaths.get(name);
  if (!path) return `${alias}."businessId"`;
  const relation = models.get(name).fields.find((field) => field.name === path[0]);
  const next = `o${depth}`;
  return `(SELECT ${owner(relation.type, next, depth + 1)} FROM ${table(relation.type)} ${next} WHERE ${relation.relationToFields.map((key, index) => `${next}.${qi(key)} = ${alias}.${qi(relation.relationFromFields[index])}`).join(" AND ")})`;
};
const jsonOwner = (column) => `(${column}->>'business_id' = ${business} OR ${column}->>'businessId' = ${business}) AND (${column}->>'business_id' IS NULL OR ${column}->>'business_id' = ${business}) AND (${column}->>'businessId' IS NULL OR ${column}->>'businessId' = ${business})`;
const pair = `EXISTS (SELECT 1 FROM public."Business" b WHERE b.id = ${business} AND b."tenantId" = ${tenant})`;
const stateExact = ["saas", "customer-settings", "staff-settings", "payroll-settings", "shift-swaps"];
const statePrefix = ["print", "printer-agent", "product-image", "shift", "report-schedule", "client-event", "qr-otp-rate"];
const ownKeys = [...stateExact.map((prefix) => `"key" = ${lit(prefix + ":")} || ${business}`), ...statePrefix.map((prefix) => `starts_with("key", ${lit(prefix + ":")} || ${business} || ':')`), `starts_with("key", 'payment-intent:' || pos_security.uri_component(${business}) || ':')`].join(" OR ");
const reserved = [...stateExact, ...statePrefix, "payment-intent"].map(lit).join(", ");
let sql = `-- Generated by scripts/generate-rls-migration.mjs. Review and commit alongside schema changes.
-- Existing table owner remains the trusted provisioning/migration role. Runtime
-- must be a different non-owner, NOBYPASSRLS role with no membership in that role.
BEGIN;
CREATE SCHEMA IF NOT EXISTS pos_security;
REVOKE ALL ON SCHEMA pos_security FROM PUBLIC;
GRANT USAGE ON SCHEMA pos_security TO PUBLIC;
CREATE OR REPLACE FUNCTION pos_security.uri_component(value text) RETURNS text
LANGUAGE plpgsql IMMUTABLE STRICT SET search_path = pg_catalog AS $fn$
DECLARE bytes bytea := convert_to(value, 'UTF8'); result text := ''; byte integer;
BEGIN
  FOR i IN 0..length(bytes)-1 LOOP
    byte := get_byte(bytes, i);
    IF (byte BETWEEN 65 AND 90) OR (byte BETWEEN 97 AND 122) OR (byte BETWEEN 48 AND 57) OR byte IN (45,95,46,33,126,42,39,40,41) THEN
      result := result || chr(byte);
    ELSE result := result || '%' || upper(lpad(to_hex(byte), 2, '0')); END IF;
  END LOOP;
  RETURN result;
END $fn$;
`;
for (const [name, model] of models) {
  if (!tenantModelPaths.has(name) && !systemModels.has(name)) throw new Error(`No RLS policy for ${name}`);
  const target = table(name);
  let predicate;
  if (tenantModelPaths.has(name)) predicate = name === "Business"
    ? `"id" = ${business} AND "tenantId" = ${tenant}`
    : `${owner(name, qi(model.dbName || name))} = ${business} AND ${pair}`;
  else if (name === "StateDocument") predicate = `(${ownKeys} OR (${jsonOwner('"data"')})) AND (split_part("key", ':', 1) NOT IN (${reserved}) OR ${ownKeys}) AND ("data"->>'business_id' IS NULL OR "data"->>'business_id' = ${business}) AND ("data"->>'businessId' IS NULL OR "data"->>'businessId' = ${business}) AND ${pair}`;
  else if (name === "AuthSession") predicate = `EXISTS (SELECT 1 FROM public."User" u WHERE u.id = "AuthSession"."userId" AND u."businessId" = ${business}) AND ${pair}`;
  else if (name === "AuthToken") predicate = `(("userId" IS NOT NULL AND EXISTS (SELECT 1 FROM public."User" u WHERE u.id = "AuthToken"."userId" AND u."businessId" = ${business})) OR ("userId" IS NULL AND (${jsonOwner('"metadata"')}))) AND ("metadata"->>'business_id' IS NULL OR "metadata"->>'business_id' = ${business}) AND ("metadata"->>'businessId' IS NULL OR "metadata"->>'businessId' = ${business}) AND ${pair}`;
  else if (name === "BackgroundJob") predicate = `(${jsonOwner('"payload"')}) AND ${pair}`;
  else if (name === "AdminCoreSyncLog") predicate = `"tenantId" = ${tenant} AND ${pair}`;
  else if (name === "DocumentSequence") predicate = `"key" IN ('invoice:' || ${business}, 'kot:' || ${business}) AND ${pair}`;
  sql += `\nALTER TABLE ${target} ENABLE ROW LEVEL SECURITY;\nALTER TABLE ${target} FORCE ROW LEVEL SECURITY;\n`;
  // FORCE also applies to the owner; explicitly retain its trusted system access.
  sql += `DO $policy$ DECLARE owner_name text; BEGIN SELECT pg_get_userbyid(relowner) INTO owner_name FROM pg_class WHERE oid=${lit(target)}::regclass; EXECUTE format('CREATE POLICY pos_system ON ${target} TO %I USING (true) WITH CHECK (true)', owner_name); END $policy$;\n`;
  if (predicate) sql += `CREATE POLICY pos_tenant ON ${target} USING (${predicate}) WITH CHECK (${predicate});\n`;
  else {
    sql += `CREATE POLICY pos_catalog_read ON ${target} FOR SELECT USING (true);\n`;
    let canonical;
    if (name === "Role") canonical = `"name" IN (${Object.keys(ROLE_DEFAULT_PERMISSIONS).map(lit).join(", ")})`;
    if (name === "Permission") canonical = `"key" IN (${STAFF_PERMISSION_KEYS.map(lit).join(", ")}) AND "label" = "key"`;
    if (name === "RolePermission") canonical = `EXISTS (SELECT 1 FROM public."Role" r JOIN public."Permission" p ON p.id = "RolePermission"."permissionId" WHERE r.id = "RolePermission"."roleId" AND (${Object.entries(ROLE_DEFAULT_PERMISSIONS).map(([role, permissions]) => `(r.name = ${lit(role)} AND p.key IN (${permissions.map(lit).join(", ")}))`).join(" OR ")}))`;
    sql += `CREATE POLICY pos_catalog_insert ON ${target} FOR INSERT WITH CHECK (${canonical} AND ${pair});\nCREATE POLICY pos_catalog_update ON ${target} FOR UPDATE USING (${canonical} AND ${pair}) WITH CHECK (${canonical} AND ${pair});\n`;
  }
  if (!tenantModelPaths.has(name)) continue;
  const checks = [];
  for (const relation of model.fields.filter((field) => field.kind === "object" && field.relationFromFields?.length && tenantModelPaths.has(field.type))) {
    const foreignOwner = owner(relation.type, "ref");
    checks.push(`IF ${relation.relationFromFields.map((key) => `NEW.${qi(key)} IS NOT NULL`).join(" AND ")} AND EXISTS (SELECT 1 FROM ${table(relation.type)} ref WHERE ${relation.relationToFields.map((key, index) => `ref.${qi(key)} = NEW.${qi(relation.relationFromFields[index])}`).join(" AND ")} AND ${foreignOwner} IS DISTINCT FROM ${owner(name, "NEW")}) THEN RAISE EXCEPTION 'Cross-business reference rejected' USING ERRCODE = '42501'; END IF;`);
  }
  if (checks.length) {
    sql += `CREATE FUNCTION pos_security.${qi("check_" + name)}() RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path = pg_catalog AS $fn$\nBEGIN\n  IF session_user = pg_get_userbyid((SELECT relowner FROM pg_class WHERE oid = TG_RELID)) THEN RETURN NEW; END IF;\n  ${checks.join("\n  ")}\n  RETURN NEW;\nEND $fn$;\nREVOKE ALL ON FUNCTION pos_security.${qi("check_" + name)}() FROM PUBLIC;\nCREATE TRIGGER pos_check_references BEFORE INSERT OR UPDATE ON ${target} FOR EACH ROW EXECUTE FUNCTION pos_security.${qi("check_" + name)}();\n`;
  }
}
sql += "\nCOMMIT;\n";
const directory = new URL("../prisma/migrations/20261024090000_tenant_row_security/", import.meta.url);
await mkdir(directory, { recursive: true });
await writeFile(new URL("migration.sql", directory), sql);
console.log(`Generated RLS policies for ${models.size} models`);
