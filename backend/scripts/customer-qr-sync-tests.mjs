import assert from "node:assert/strict";
import { randomUUID } from "node:crypto";
import prisma from "../src/database/prisma/client.js";
import env from "../src/config/env.js";
import { connectDatabase } from "../src/config/db.js";
import { saasService } from "../src/core/saas/saas.service.js";
import { customersService } from "../src/core/customers/customers.service.js";
import { billingService } from "../src/core/billing/billing.service.js";
import { tableManagementService } from "../src/features/sales-extensions/table-management/table-management.service.js";
import { qrOrderingService } from "../src/features/sales-extensions/qr-ordering/qr-ordering.service.js";
import { kotService } from "../src/features/kitchen/kot/kot.service.js";
import { runTenantScope } from "../src/database/prisma/tenant-context.js";
import { stopRealtime } from "../src/services/realtime/realtime.service.js";

const id = `qr-customers-${randomUUID()}`, tenantId = `tenant-${id}`, other = `${id}-other`;
const before = env.admincore.enabled;
const scoped = (work) => runTenantScope({ businessId: id, tenantId }, work);
try {
  env.admincore.enabled = false;
  await connectDatabase();
  await saasService.upsertTenantFromAdminCore({ business_id: id, tenant_id: tenantId, name: id, plan: "growth", owner_email: `${id}@example.invalid`, owner_password: randomUUID() });
  await prisma.business.create({ data: { id: other, tenantId: other, name: other } });
  const owner = await prisma.user.findFirst({ where: { businessId: id }, include: { role: true } });
  const actor = { id: owner.id, name: owner.name, role: owner.role.name };
  const outlet = await prisma.outlet.create({ data: { businessId: id, name: "Main", code: "MAIN" } });
  const product = await prisma.product.create({ data: { businessId: id, name: "Sandwich", category: "Food", price: 100, stock: 20 } });
  await prisma.customer.create({ data: { businessId: id, phone: "9845012345", name: "Saved contact name" } });
  await prisma.tableManagementSettings.upsert({ where: { businessId: id }, create: { businessId: id, capabilities: { qrOrderingEnabled: true } }, update: { capabilities: { qrOrderingEnabled: true } } });
  const table = await prisma.diningTable.create({ data: { businessId: id, name: "S1", meta: { outlet_id: outlet.id } } });
  const qr = await tableManagementService.upsertTableQrCode({ businessId: id, tenantId, tableId: table.id });
  const ordered = await runTenantScope({}, () => qrOrderingService.createOrder({ token: qr.token, payload: { customerName: "QR Guest", customerPhone: "9845012345", client_request_id: randomUUID(), items: [{ productId: product.id, quantity: 1 }] } }));
  const order = await prisma.order.findFirst({ where: { businessId: id } });
  assert.ok(ordered);
  let guest = await prisma.customer.findUnique({ where: { businessId_phone: { businessId: id, phone: "9845012345" } } });
  assert.equal(guest.name, "Saved contact name", "A QR guest must not overwrite a staff-maintained contact name");
  assert.equal(guest.visitCount, 0);
  assert.equal(guest.loyaltyPoints, 0);
  assert.equal(Number(guest.totalSpent), 0);
  const historical = await prisma.bill.create({ data: { businessId: id, customerName: "Existing Guest", currency: "INR", subtotal: 80, tax: 0, total: 80, status: "issued", metadata: { customer_phone: "9000000001", payment_status: "paid" } } });
  await prisma.bill.create({ data: { businessId: other, customerName: "Other Guest", currency: "INR", subtotal: 90, tax: 0, total: 90, status: "issued", metadata: { customer_phone: "9000000002" } } });
  const [rows, stats] = await scoped(() => Promise.all([customersService.search({ businessId: id, query: {} }), customersService.stats({ businessId: id })]));
  assert.equal(rows.length, 2, "Unspecified celebrations must not hide guests");
  assert.deepEqual(rows.find((row) => row.id === guest.id).qr_guest_names, ["QR Guest"]);
  const byQrName = await scoped(() => customersService.search({ businessId: id, query: { search: "QR Guest" } }));
  assert.equal(byQrName.length, 1);
  assert.equal(byQrName[0].id, guest.id, "Searching a QR name must find the existing phone profile");
  assert.equal(stats.customers, 2);
  assert.equal((await scoped(() => customersService.search({ businessId: id, query: { celebrations: "" } }))).length, 2);
  const imported = await prisma.customer.findUnique({ where: { businessId_phone: { businessId: id, phone: "9000000001" } } });
  assert.equal(imported.visitCount, 1);
  assert.equal(Number(imported.totalSpent), 80);
  assert.equal(imported.loyaltyPoints, 0, "History import must not invent retroactive points");
  await scoped(() => customersService.stats({ businessId: id }));
  assert.equal((await prisma.customer.findUnique({ where: { id: imported.id } })).visitCount, 1);
  assert.equal(await prisma.customer.count({ where: { businessId: other } }), 0);
  assert.equal((await prisma.bill.findUnique({ where: { id: historical.id } })).metadata.customer_id, imported.id);
  await scoped(() => qrOrderingService.approveOrder({ businessId: id, tenantId, orderId: order.id, actor }));
  const ticket = await prisma.kitchenTicket.findFirst({ where: { orderId: order.id } });
  assert.equal((await scoped(() => kotService.listTickets({ tenantId, active: true, outletIds: [outlet.id], limit: 1 }))).items[0].id, ticket.id);
  const bill = await scoped(() => billingService.createInvoice({ tenantId, user: actor, payload: { order_id: order.id, outlet_id: outlet.id, payment_type: "Cash", items: [{ id: product.id, quantity: 1 }] } }));
  const saved = await prisma.bill.findUnique({ where: { id: bill.id } });
  assert.equal(saved.metadata.customer_id, guest.id, "QR checkout must inherit the guest phone");
  assert.equal(saved.metadata.customer_phone, "9845012345");
  guest = await prisma.customer.findUnique({ where: { id: guest.id } });
  assert.equal(guest.visitCount, 1);
  assert.ok(Number(guest.totalSpent) >= 100);
  // An unbilled historical QR guest is imported, but stays erased after a reload.
  await prisma.order.create({ data: { businessId: id, customerName: "Old QR Guest", channel: "qr", status: "qr_pending_approval", total: 100, metadata: { customer_phone: "9000000003" } } });
  await scoped(() => customersService.stats({ businessId: id }));
  const oldGuest = await prisma.customer.findUnique({ where: { businessId_phone: { businessId: id, phone: "9000000003" } } });
  assert.equal(oldGuest.visitCount, 0);
  await scoped(() => customersService.anonymize({ businessId: id, customerId: oldGuest.id, actor, payload: { reason: "Test erasure" } }));
  await scoped(() => customersService.stats({ businessId: id }));
  assert.equal(await prisma.customer.count({ where: { businessId: id, phone: "9000000003" } }), 0);
  console.log("QR/customer sync passed: immediate pending-order profile, default filters, historical recovery, no retroactive rewards, no duplicate visits, tenant isolation, inherited billing phone and retained erasure");
} finally {
  env.admincore.enabled = before;
  const users = await prisma.user.findMany({ where: { businessId: id }, select: { id: true } });
  await prisma.authSession.deleteMany({ where: { userId: { in: users.map((row) => row.id) } } });
  await prisma.business.deleteMany({ where: { id: { in: [id, other] } } });
  await prisma.stateDocument.deleteMany({ where: { key: { contains: id } } });
  await stopRealtime();
  await prisma.$disconnect();
}
