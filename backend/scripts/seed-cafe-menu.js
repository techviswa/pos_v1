async function upsertInventory(businessId) {
  const records = [];

  for (const item of inventoryItems) {
    const record = await prisma.inventoryItem.upsert({
      where: {
        businessId_name: {
          businessId,
          name: item.name,
        },
      },
      update: {
        stock: item.stock,
        unit: item.unit,
        reorderLevel: item.reorderLevel,
        conversionCost: item.conversionCost,
      },
      create: {
        businessId,
        name: item.name,
        stock: item.stock,
        unit: item.unit,
        reorderLevel: item.reorderLevel,
        conversionCost: item.conversionCost,
      },
    });

    records.push(record);
  }

  return new Map(records.map((item) => [item.name, item]));
}

async function upsertProduct(businessId, product) {
  const saved = await prisma.product.upsert({
    where: {
      businessId_name: {
        businessId,
        name: product.name,
      },
    },
    update: {
      price: product.price,
      costPrice: product.cost_price,
      stock: product.stock,
      active: product.active,
      category: product.category,
      dietaryType: product.dietary_type,
      channelSettings: product.channel_settings || createChannelSettings(product.price),
      removalOptions: product.removal_options,
      recipeLines: product.recipe_lines,
    },
    create: {
      businessId,
      name: product.name,
      price: product.price,
      costPrice: product.cost_price,
      stock: product.stock,
      active: product.active,
      category: product.category,
      dietaryType: product.dietary_type,
      channelSettings: product.channel_settings || createChannelSettings(product.price),
      removalOptions: product.removal_options,
      recipeLines: product.recipe_lines,
    },
  });

  await prisma.variation.deleteMany({ where: { productId: saved.id } });
  await prisma.addon.deleteMany({ where: { productId: saved.id } });

  if (product.variation_options?.length) {
    await prisma.variation.createMany({
      data: product.variation_options.map((variation) => ({
        productId: saved.id,
        name: variation.name,
        price: variation.price || 0,
        recipeLines: variation.recipe_lines || [],
      })),
    });
  }

  if (product.addon_options?.length) {
    await prisma.addon.createMany({
      data: product.addon_options.map((addon) => ({
        productId: saved.id,
        name: addon.name,
        price: addon.price || 0,
        recipeLines: addon.recipe_lines || [],
      })),
    });
  }
}

async function main() {
  const business = await ensureBusiness();
  const inventoryMap = await upsertInventory(business.id);
  const menu = buildMenu(inventoryMap);

  for (const product of menu) {
    await upsertProduct(business.id, product);
  }

  console.log(`Seeded ${inventoryItems.length} inventory items and ${menu.length} menu products.`);
}

main()
  .then(async () => {
    await prisma.$disconnect();
  })
  .catch(async (error) => {
    console.error(error);
    await prisma.$disconnect();
    process.exit(1);
  });
