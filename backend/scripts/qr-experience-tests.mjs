import assert from "node:assert/strict";
import http from "node:http";
import { randomUUID } from "node:crypto";
import app from "../src/app.js";
import prisma from "../src/database/prisma/client.js";
import env from "../src/config/env.js";
import { connectDatabase } from "../src/config/db.js";
import { saasService } from "../src/core/saas/saas.service.js";
import { usersService } from "../src/core/users/users.service.js";
import { tableManagementService } from "../src/features/sales-extensions/table-management/table-management.service.js";
import { priceRulesService } from "../src/core/menu/price-rules.service.js";
import { billingService } from "../src/core/billing/billing.service.js";
import { signFeedbackToken } from "../src/core/feedback/feedback-token.js";
import { reviewKey } from "../src/features/sales-extensions/qr-ordering/qr-experience.service.js";
import { stopRealtime } from "../src/services/realtime/realtime.service.js";

const suffix = randomUUID(), a = `exp-a-${suffix}`, b = `exp-b-${suffix}`, password = randomUUID();
const scope = (businessId) => ({ businessId, tenantId: `tenant-${businessId}` });
const api = http.createServer(app), prior = env.admincore.enabled;
let base, checks = 0;
const eq = (actual, expected) => { assert.deepEqual(actual, expected); checks++; };
const call = async (method, path, body, session) => {
  const response = await fetch(base + "/api/public/qr" + path, { method, headers: { "content-type": "application/json", ...(session ? { "x-cf-session-id": session } : {}) }, ...(body ? { body: JSON.stringify(body) } : {}) });
  const json = await response.json(); return { status: response.status, data: json.data, json };
};
try {
  env.admincore.enabled = false; await connectDatabase();
  for (const id of [a, b]) {
    await prisma.business.create({ data: { id, tenantId: scope(id).tenantId, name: "Experience fixture" } });
    await saasService.updateSubscription({ businessId: id, payload: { plan: "growth", subscription_status: "active" } });
    await prisma.tableManagementSettings.create({ data: { businessId: id, capabilities: { qrOrderingEnabled: true } } });
  }
  const outlet = await prisma.outlet.create({ data: { businessId: a, code: "A", name: "Main" } });
  const other = await prisma.outlet.create({ data: { businessId: a, code: "B", name: "Other" } });
  const make = (name, businessId, permissions, outlets) => usersService.createUser({ ...scope(businessId), payload: { name, role: name === "Viewer" ? "Cashier" : "Owner", email: `${name}-${suffix}@example.invalid`, password, profile_required: false, ...(permissions ? { permissions } : {}), assigned_outlet_ids: outlets || [] } });
  const [owner, foreign, viewer] = await Promise.all([make("Owner", a), make("Foreign", b), make("Viewer", a, ["reports"], [outlet.id])]);
  await new Promise((resolve) => api.listen(0, "127.0.0.1", resolve)); base = `http://127.0.0.1:${api.address().port}`;
  const login = async (user) => {
    const response = await fetch(base + "/api/auth/login", { method: "POST", headers: { "content-type": "application/json" }, body: JSON.stringify({ email: user.email, password }) });
    eq(response.status, 200); return (await response.json()).data.session_id;
  };
  const [ownerS, foreignS, viewerS] = await Promise.all([owner, foreign, viewer].map(login));
  const product = await prisma.product.create({ data: { businessId: a, name: "Offer meal", category: "Food", price: 100, stock: 100 } });
  const rule = await priceRulesService.create({ ...scope(a), payload: { name: "Lunch saving", discount_type: "percent_off", value: 25, channels: ["QR"], outlet_ids: [outlet.id], product_ids: [product.id], start_time: "00:00", end_time: "00:00" } });
  await priceRulesService.create({ ...scope(a), payload: { name: "Inactive", active: false, discount_type: "percent_off", value: 80, channels: ["QR"], start_time: "00:00", end_time: "00:00" } });
  const table = await prisma.diningTable.create({ data: { businessId: a, name: "T-main", meta: { outlet_id: outlet.id } } });
  const tableB = await prisma.diningTable.create({ data: { businessId: a, name: "T-other", meta: { outlet_id: other.id } } });
  const [qr, qrB] = await Promise.all([table, tableB].map((table) => tableManagementService.upsertTableQrCode({ ...scope(a), tableId: table.id })));
  const menu = (await call("GET", `/${qr.token}/menu`)).data, menuB = (await call("GET", `/${qrB.token}/menu`)).data;
  eq(menu.items[0].price, 75); eq(menu.items[0].list_price, 100); eq(menu.items[0].price_rule.id, rule.id);
  eq(menuB.items[0].price, 100); eq(menuB.items[0].price_rule, null);
  await call("GET", `/${qr.token}/menu?refresh=1`);
  const createOrder = async (qrToken, quantity) => {
    const order = await call("POST", `/${qrToken}/orders`, { client_request_id: randomUUID(), items: [{ product_id: product.id, quantity }] });
    eq(order.status, 201); eq((await call("POST", `/orders/${order.data.id}/approve`, {}, ownerS)).status, 200); return order.data;
  };
  const order = await createOrder(qr.token, 2), otherOrder = await createOrder(qrB.token, 1);
  eq(order.total, 150); eq(otherOrder.total, 100);
  const feedbackPath = `/orders/${order.tracking_token}/feedback`;
  eq((await call("GET", feedbackPath)).data.eligible, false);
  eq((await call("POST", feedbackPath, { rating: 5 })).status, 409);
  await call("POST", `/orders/${order.tracking_token}/checkout/request`, { points: 0 });
  const issued = await call("POST", `/checkout/${order.id}/issue`, {}, ownerS); eq(issued.status, 200);
  await billingService.addPayment({ tenantId: scope(a).tenantId, invoiceId: issued.data.id, user: owner, payload: { method: "Cash", amount: issued.data.total, client_request_id: randomUUID() } });
  eq((await call("GET", feedbackPath)).data.eligible, true);
  eq((await call("POST", feedbackPath, { rating: 0 })).status, 400);
  eq((await call("POST", feedbackPath, { rating: 4, service_rating: 6 })).status, 400);
  eq((await call("POST", feedbackPath, { rating: 4, topics: ["invalid"] })).status, 400);
  eq((await call("POST", feedbackPath, { rating: 4, comment: "x".repeat(1001) })).status, 400);
  const raced = await Promise.all(Array.from({ length: 5 }, () => call("POST", feedbackPath, { rating: 2, food_rating: 4, service_rating: 1, topics: ["speed", "staff"], comment: "Food was good; service took too long." })));
  eq(raced.filter((result) => result.status === 201).length, 1); eq(raced.filter((result) => result.status === 200).length, 4);
  eq(await prisma.feedback.count({ where: { businessId: a, billId: issued.data.id } }), 1);
  const feedback = await prisma.feedback.findFirst({ where: { businessId: a, billId: issued.data.id } });
  eq((await call("GET", feedbackPath)).data.already_submitted, true);
  const receiptForm = await fetch(`${base}/api/feedback/form/${signFeedbackToken(issued.data.id)}`);
  eq((await receiptForm.json()).data.already_submitted, true);
  const now = Date.now(), started = new Date(now - 60 * 60000);
  const rawOrder = await prisma.order.findUnique({ where: { id: order.id } });
  await prisma.order.update({ where: { id: order.id }, data: { createdAt: started, metadata: { ...rawOrder.metadata, approved_at: new Date(started.getTime() + 2 * 60000).toISOString(), kot: { ...rawOrder.metadata.kot, prep_started_at: new Date(now - 30 * 60000).toISOString(), ready_at: new Date(now - 5 * 60000).toISOString(), estimated_prep_minutes: 20 } } } });
  const rawOther = await prisma.order.findUnique({ where: { id: otherOrder.id } });
  await prisma.order.update({ where: { id: otherOrder.id }, data: { createdAt: started, metadata: { ...rawOther.metadata, approved_at: new Date(started.getTime() + 4 * 60000).toISOString() } } });
  await prisma.kitchenTicket.updateMany({ where: { orderId: order.id }, data: { status: "ready" } });
  await prisma.tableSession.updateMany({ where: { id: { in: [menu.table_session.id, menuB.table_session.id] } }, data: { openedAt: started } });
  await prisma.tableSession.update({ where: { id: menuB.table_session.id }, data: { status: "closed", closedAt: new Date() } });
  const requestRow = async (kind, session, outletId, status, accepted, resolved) => {
    const id = randomUUID();
    await prisma.stateDocument.create({ data: { key: `assistance:${a}:${id}`, data: { id, business_id: a, session_id: session, outlet_id: outletId, kind, status, created_at: new Date(now - 10 * 60000).toISOString(), accepted_at: accepted ? new Date(now - 8 * 60000).toISOString() : null, resolved_at: resolved ? new Date(now - 6 * 60000).toISOString() : null } } });
  };
  await requestRow("water", menu.table_session.id, outlet.id, "resolved", true, true);
  await requestRow("waiter", menu.table_session.id, outlet.id, "pending", false, false);
  await requestRow("bill", menuB.table_session.id, other.id, "pending", false, false);
  eq((await call("GET", "/analytics/service")).status, 401);
  eq((await call("GET", "/analytics/service?from=2026-02-30&to=2026-03-01", null, ownerS)).status, 400);
  eq((await call("GET", "/analytics/service?from=2026-03-02&to=2026-03-01", null, ownerS)).status, 400);
  eq((await call("GET", "/analytics/service?from=2026-01-01&to=2026-12-31", null, ownerS)).status, 400);
  const analytics = (await call("GET", "/analytics/service", null, ownerS)).data;
  eq(analytics.summary.orders, 2); eq(analytics.summary.menu_opens, 2); eq(analytics.summary.average_rating, 2); eq(analytics.summary.needs_attention, 1);
  eq(analytics.summary.median_approval_minutes, 3);
  eq(analytics.summary.median_prep_minutes, 25); eq(analytics.summary.late_prep, 1);
  eq(analytics.summary.assistance_requests, 3); eq(analytics.summary.open_requests, 1); eq(analytics.summary.overdue_requests, 1);
  eq(analytics.assistance.find((row) => row.kind === "water").median_response_minutes, 2);
  eq(analytics.assistance.find((row) => row.kind === "water").median_resolution_minutes, 4);
  eq(analytics.assistance.find((row) => row.kind === "bill").expired, 1);
  eq(analytics.offers[0].savings, 50); eq(analytics.offers[0].orders, 1); eq(analytics.offers[0].units, 2);
  const scoped = (await call("GET", "/analytics/service", null, viewerS)).data;
  eq(scoped.summary.orders, 1); eq(scoped.summary.menu_opens, 1); eq(scoped.summary.assistance_requests, 2);
  eq((await call("GET", `/analytics/service?outlet_id=${other.id}`, null, viewerS)).status, 403);
  const foreignStats = (await call("GET", "/analytics/service", null, foreignS)).data;
  eq(foreignStats.summary.orders, 0); eq(foreignStats.summary.average_rating, null); eq(foreignStats.summary.median_prep_minutes, null);
  eq((await call("POST", `/analytics/feedback/${feedback.id}`, { status: "resolved" }, foreignS)).status, 404);
  eq((await call("POST", `/analytics/feedback/${feedback.id}`, { status: "resolved" }, viewerS)).status, 403);
  eq((await call("POST", `/analytics/feedback/${feedback.id}`, { status: "invalid" }, ownerS)).status, 400);
  eq((await call("POST", `/analytics/feedback/${feedback.id}`, { status: "resolved", internal_note: "Investigated wait time." }, ownerS)).status, 200);
  eq((await call("GET", "/analytics/service", null, ownerS)).data.summary.needs_attention, 0);
  eq((await prisma.stateDocument.findUnique({ where: { key: reviewKey(a, feedback.id) } })).data.history.length, 1);
  eq(JSON.stringify((await call("GET", feedbackPath)).data).includes("Investigated"), false);
  eq((await call("GET", "/orders/nonexistent/feedback")).status, 404);
  console.log(`QR experience passed: ${checks} checks for offer pricing/scope, paid-only one-per-bill feedback, private follow-up, real service metrics, date validation and outlet/tenant isolation.`);
} finally {
  env.admincore.enabled = prior;
  if (api.listening) await new Promise((resolve) => api.close(resolve));
  const users = await prisma.user.findMany({ where: { businessId: { in: [a, b] } }, select: { id: true } });
  await prisma.authSession.deleteMany({ where: { userId: { in: users.map((user) => user.id) } } });
  await prisma.business.deleteMany({ where: { id: { in: [a, b] } } });
  await prisma.stateDocument.deleteMany({ where: { key: { contains: suffix } } });
  await stopRealtime(); await prisma.$disconnect();
}
